def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace("\"", "\\\"")


def gen_collection(name: str, collection_id: str) -> str:
    data = json.loads((SCRIPTS / f"qurantime_{name}.json").read_text(encoding="utf-8"))
    virtues = VIRTUES[name]
    repeats = REPEATS[name]
    lines = [f'    fun {name}Items(): List<QurantimeItem> = listOf(']
    for i, item in enumerate(data):
        v = virtues[i] if i < len(virtues) else ""
        r = repeats[i] if i < len(repeats) else 1
        aid = item["audio_id"]
        lines.append(
            f'        QurantimeItem("{esc(item["text"])}", "{esc(v)}", {r}, "audio/azkar/qt_{aid:02d}.mp3"),'
        )
    lines.append("    )")
    return "\n".join(lines)


