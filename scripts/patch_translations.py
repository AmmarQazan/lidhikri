def patch(locale_dir: str, translations: dict) -> None:
    path = BASE / locale_dir / "strings.xml"
    tree = ET.parse(path)
    root = tree.getroot()
    existing = {e.get("name") for e in root if e.tag == "string"}
    en_path = BASE / "values" / "strings.xml"
    en_tree = ET.parse(en_path)
    en_keys = {e.get("name"): e.text or "" for e in en_tree.getroot() if e.tag == "string"}
    missing = sorted(set(en_keys) - existing)
    added = 0
    for key in missing:
        text = translations.get(key)
        if text is None:
            print(f"WARN: no translation for {key} in {locale_dir}")
            text = en_keys[key]
        # Android XML escaping
        text = text.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n")
        elem = ET.SubElement(root, "string", name=key)
        elem.text = text
        added += 1
    # Sort children by name for consistency
    children = sorted(root.findall("string"), key=lambda e: e.get("name", ""))
    root[:] = children
    tree.write(path, encoding="utf-8", xml_declaration=True)
    print(f"{locale_dir}: added {added} keys, total {len(children)}")


